#!/usr/bin/env python3
"""Generate sim/test_picture.h, the simulator's test pictures. An aurora over mountains, and the same with a
moon. They share one 16-colour palette, so the moon one can go as a patch of the rows that changed."""

import math
import os
import random

from PIL import Image, ImageDraw

W, H = 320, 240


def scene(moon):
    random.seed(7)  # same stars in both pictures
    img = Image.new("RGB", (W, H))
    px = img.load()
    for y in range(H):
        t = y / H
        c = (int(6 + 14 * t), int(12 + 50 * t), int(34 + 48 * t))
        for x in range(W):
            px[x, y] = c
    # aurora: soft green curtains
    for x in range(W):
        top = 46 + 18 * math.sin(x / 37) + 8 * math.sin(x / 13 + 1)
        for y in range(int(top), int(top + 70)):
            a = max(0.0, 1 - (y - top) / 70) * (0.55 + 0.45 * math.sin(x / 9) ** 2)
            r, g, b = px[x, y]
            px[x, y] = (int(r + (60 - r) * a * 0.6), int(g + (230 - g) * a), int(b + (150 - b) * a * 0.7))
    d = ImageDraw.Draw(img)
    for _ in range(36):
        x, y = random.randrange(W), random.randrange(4, 110)
        d.point((x, y), fill=(235, 240, 255))
    if moon:
        d.ellipse((250, 22, 278, 50), fill=(236, 234, 214))
        d.ellipse((259, 20, 287, 46), fill=px[300, 30])  # crescent
    d.polygon(
        [
            (0, 170),
            (40, 128),
            (70, 150),
            (115, 104),
            (160, 146),
            (205, 118),
            (250, 152),
            (290, 126),
            (320, 140),
            (320, 240),
            (0, 240),
        ],
        fill=(36, 52, 78),
    )
    d.polygon([(115, 104), (104, 116), (112, 114), (121, 122), (128, 113)], fill=(205, 218, 232))
    d.polygon([(205, 118), (196, 128), (204, 126), (212, 132), (217, 125)], fill=(205, 218, 232))
    d.polygon(
        [(0, 200), (60, 168), (110, 190), (170, 160), (230, 192), (280, 172), (320, 186), (320, 240), (0, 240)],
        fill=(14, 22, 34),
    )
    d.rectangle((60, 196, 76, 210), fill=(28, 30, 34))  # cabin
    d.polygon([(56, 197), (68, 187), (80, 197)], fill=(28, 30, 34))
    d.rectangle((64, 200, 68, 204), fill=(255, 196, 92))
    return img


def packed_rows(q):
    """Two 4-bit pixels per byte, left one in the high nibble."""
    p = q.load()
    rows = []
    for y in range(H):
        rows.append(bytes((p[x, y] << 4) | p[x + 1, y] for x in range(0, W, 2)))
    return rows


def main():
    # 13 colours from the picture, plus snow, moon and the lit window, which are too small for the quantizer
    auto = scene(False).quantize(colors=13, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal_img = Image.new("P", (1, 1))
    pal_img.putpalette(auto.getpalette()[:39] + [205, 218, 232, 236, 234, 214, 255, 196, 92])
    # map both with the same palette so the unchanged areas come out identical
    base = scene(False).quantize(palette=pal_img, dither=Image.Dither.NONE)
    moon = scene(True).quantize(palette=pal_img, dither=Image.Dither.NONE)
    pal = pal_img.getpalette()[:48]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "test_picture.h")
    with open(out, "w") as f:
        f.write("// generated by mkpicture.py\n#define TP_W %d\n#define TP_H %d\n" % (W, H))
        f.write(
            "static const uint32_t tp_palette[16] = {%s};\n"
            % ", ".join("0x%02X%02X%02X" % tuple(pal[i * 3 : i * 3 + 3]) for i in range(16))
        )
        for name, img in (("tp_base", base), ("tp_moon", moon)):
            f.write("static const uint8_t %s[TP_H][TP_W / 2] = {\n" % name)
            for r in packed_rows(img):
                f.write("  {%s},\n" % ",".join(str(b) for b in r))
            f.write("};\n")
    base.convert("RGB").resize((W * 2, H * 2), Image.NEAREST).save(out.replace(".h", ".png"))
    print("wrote", out)


if __name__ == "__main__":
    main()
