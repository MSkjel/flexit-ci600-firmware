#!/usr/bin/env python3
"""Write the authors header for the About pages from git, most commits first.

    mkauthors.py ROOT ESP_REPO OUT [NAME...] [--esp NAME...]   the NAMEs instead of git's

The panel's authors come from ROOT's history and the ESP integration's from ESP_REPO's. OUT is only written when it
changes, so make rebuilds only then. Without git, or without the ESP repo, that list is empty.
"""

import os
import re
import subprocess
import sys
import unicodedata
from collections import Counter

from mkfonts import TEXT_RANGE

MAX_NAMES = 16
MAX_LEN = 24  # characters, fits a line in font_f16
# letters NFKD doesn't take apart into ASCII
EXTRA = {
    "ß": "ss",
    "Ð": "D",
    "ð": "d",
    "Đ": "D",
    "đ": "d",
    "Ł": "L",
    "ł": "l",
    "Œ": "OE",
    "œ": "oe",
    "Þ": "Th",
    "þ": "th",
}


def font_chars():
    """The characters the text fonts have"""
    chars = set()
    for part in TEXT_RANGE.split(","):
        lo, _, hi = part.partition("-")
        chars.update(chr(c) for c in range(int(lo, 16), int(hi or lo, 16) + 1))
    return chars


def clean(name, chars):
    """name in characters the fonts have, others as ASCII or left out"""
    out = ""
    for c in name:
        if c.isspace():
            out += " "
        elif c in chars:
            out += c
        else:
            out += "".join(a for a in EXTRA.get(c) or unicodedata.normalize("NFKD", c) if a.isascii() and a in chars)
    return " ".join(out.split())[:MAX_LEN].strip()


def person(email):
    """Who wrote a commit, by email. GitHub's noreply addresses go by the account's number, which a rename keeps."""
    e = email.strip().rstrip(".").casefold()
    m = re.fullmatch(r"(\d+)\+[^@]+@users\.noreply\.github\.com", e)
    return m.group(1) if m else e


def from_git(root):
    """root's authors, most commits first, each by the name they used most"""
    try:
        log = subprocess.run(
            ["git", "-C", root, "log", "--format=%aN%x09%aE"], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return []
    names = {}  # person: Counter of the names on their commits
    for line in log.stdout.splitlines():
        name, _, email = line.partition("\t")
        name = name.strip()
        if not name or name.endswith("[bot]") or name.startswith("github-actions"):
            continue
        names.setdefault(person(email) or name.casefold(), Counter())[name] += 1
    people = [(c.most_common(1)[0][0], sum(c.values())) for c in names.values()]
    return [n for n, _ in sorted(people, key=lambda p: (-p[1], p[0].casefold()))]


def keep(names, chars):
    """names cleaned for the fonts, each once, at most MAX_NAMES"""
    out = []
    for n in names:
        c = clean(n, chars)
        if c and c.casefold() not in (k.casefold() for k in out):
            out.append(c)
    return out[:MAX_NAMES]


def macro(name, names):
    quoted = ['X("%s")' % n.replace("\\", "\\\\").replace('"', '\\"') for n in names]
    return "#define %s_N %d\n#define %s(X) %s\n" % (name, len(names), name, ", \\\n  ".join(quoted))


def main():
    root, esp_repo, out, args = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    panel, esp = args, []
    if "--esp" in args:
        i = args.index("--esp")
        panel, esp = args[:i], args[i + 1 :]
    chars = font_chars()
    text = "// Generated by tools/mkauthors.py\n"
    text += macro("AUTHORS", keep(panel or from_git(root), chars))
    text += macro("ESP_AUTHORS", keep(esp or from_git(esp_repo), chars))
    try:
        with open(out, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
