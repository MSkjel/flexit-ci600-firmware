#!/usr/bin/env python3
"""Write the authors header for the About pages from git, most commits first.

    mkauthors.py ROOT OUT [NAME...]   the NAMEs instead of git's

OUT is only written when it changes, so make rebuilds only then. Without git the list is empty.
"""

import ast
import os
import subprocess
import sys
import unicodedata
from collections import Counter

MAX_NAMES = 16
MAX_LEN = 24  # characters, fits a line in font_f16
# letters NFKD doesn't take apart into ASCII
EXTRA = {
    "ß": "ss",
    "Ð": "D",
    "ð": "d",
    "Đ": "D",
    "đ": "d",
    "Ł": "L",
    "ł": "l",
    "Œ": "OE",
    "œ": "oe",
    "Þ": "Th",
    "þ": "th",
}


def font_chars(root):
    """TEXT_RANGE of tools/mkfonts.py as a set. Parsed, importing it needs fontTools."""
    with open(os.path.join(root, "tools", "mkfonts.py"), encoding="utf-8") as f:
        tree = ast.parse(f.read())
    text = next(
        ast.literal_eval(n.value)
        for n in tree.body
        if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "TEXT_RANGE" for t in n.targets)
    )
    chars = set()
    for part in text.split(","):
        lo, _, hi = part.partition("-")
        chars.update(chr(c) for c in range(int(lo, 16), int(hi or lo, 16) + 1))
    return chars


def clean(name, chars):
    """name in characters the fonts have, others as ASCII or left out"""
    out = ""
    for c in name:
        if c.isspace():
            out += " "
        elif c in chars:
            out += c
        else:
            out += "".join(a for a in EXTRA.get(c) or unicodedata.normalize("NFKD", c) if a.isascii() and a in chars)
    return " ".join(out.split())[:MAX_LEN].strip()


def from_git(root):
    try:
        log = subprocess.run(["git", "-C", root, "log", "--format=%aN"], capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return []
    counts = Counter(n.strip() for n in log.stdout.splitlines() if n.strip())
    people = [n for n in counts if not n.endswith("[bot]") and not n.startswith("github-actions")]
    return sorted(people, key=lambda n: (-counts[n], n.casefold()))


def main():
    root, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    chars = font_chars(root)
    keep = []
    for n in names or from_git(root):
        c = clean(n, chars)
        if c and c.casefold() not in (k.casefold() for k in keep):
            keep.append(c)
    keep = keep[:MAX_NAMES]
    quoted = ['X("%s")' % n.replace("\\", "\\\\").replace('"', '\\"') for n in keep]
    text = "// Generated by tools/mkauthors.py\n#define AUTHORS_N %d\n#define AUTHORS(X) %s\n" % (
        len(keep),
        ", \\\n  ".join(quoted),
    )
    try:
        with open(out, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
